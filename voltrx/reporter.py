def generate_html_report(summary, output_path="report.html"):
    endpoints_rows = ""
    for ep, count in summary.get("top_endpoints", []):
        endpoints_rows += f"<tr><td><code>{ep}</code></td><td><strong>{count:,}</strong></td></tr>\n"

    ips_rows = ""
    for ip, count in summary.get("top_ips", []):
        ips_rows += f"<tr><td><code>{ip}</code></td><td><strong>{count:,}</strong></td></tr>\n"

    security_section = ""
    alerts = summary.get("security_alerts", [])
    if alerts:
        security_rows = ""
        for a in alerts:
            security_rows += f"<tr><td><code>{a['ip']}</code></td><td><span class='badge badge-danger'>{a['type']}</span></td><td><code>{a['endpoint']}</code></td><td>{a['time']}</td></tr>\n"

        security_section = f"""
        <div class="section-title" style="color: var(--accent-red);">🚨 Security & Suspicious Activity Detected</div>
        <table>
            <thead>
                <tr>
                    <th>Client IP</th>
                    <th>Alert Type</th>
                    <th>Target Endpoint</th>
                    <th>Timestamp</th>
                </tr>
            </thead>
            <tbody>
                {security_rows}
            </tbody>
        </table>
        """

    html = HTML_TEMPLATE
    html = html.replace("{{TOTAL_REQUESTS}}", f"{summary.get('total_requests', 0):,}")
    html = html.replace("{{UNIQUE_VISITORS}}", f"{summary.get('unique_visitors', 0):,}")
    html = html.replace("{{BANDWIDTH}}", str(summary.get("total_bandwidth_mb", 0)))
    html = html.replace("{{SECURITY_ALERTS}}", str(summary.get("security_alerts_count", 0)))
    html = html.replace("{{ENDPOINTS_ROWS}}", endpoints_rows or "<tr><td colspan='2'>No data</td></tr>")
    html = html.replace("{{IPS_ROWS}}", ips_rows or "<tr><td colspan='2'>No data</td></tr>")
    html = html.replace("{{SECURITY_SECTION}}", security_section)

    with open(output_path, "w", encoding="utf-8") as f:
        f.write(html)

def export_json_report(summary, output_path="report.json"):
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)
